#!/usr/bin/env python3
"""Regenerate the README "Coverage at a glance" count block from repo data.

Counts come from build_mitre_coverage.build_coverage(), the same logic that writes
content/mitre/coverage.json, so README and coverage.json cannot disagree.
Only the text between the README_COUNTS markers is rewritten.

Usage:
  python pipelines/validate/build_readme_counts.py          # rewrite README.md
  python pipelines/validate/build_readme_counts.py --check  # exit 1 if README is stale
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path
from typing import Any, Dict, List

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_mitre_coverage import _iter_detection_files, _load_yaml, _normalize, _repo_root, build_coverage  # noqa: E402

BEGIN = "<!-- README_COUNTS:BEGIN (generated by pipelines/validate/build_readme_counts.py; do not edit by hand) -->"
END = "<!-- README_COUNTS:END -->"

PACK_LABELS = {
    "windows": "Windows",
    "cloud": "Cloud",
    "github": "GitHub",
    "vmware": "VMware ESXi",
    "claude": "Claude compliance",
    "beyondtrust": "BeyondTrust",
    "okta": "Okta",
    "paloalto": "Palo Alto",
}


def _extra_counts(detections_root: Path) -> Dict[str, Any]:
    """Splunk pack split and Sigma metadata, using the same file walk and id filter as coverage."""
    packs: Counter = Counter()
    sigma_meta = 0
    sigma_files = 0
    for p in _iter_detection_files(detections_root):
        obj = _load_yaml(p)
        if isinstance(obj, dict) and "logsource" in obj and "detection" in obj:
            sigma_files += 1
        for det in _normalize(p, obj):
            if not isinstance(det.get("id"), str):
                continue
            rel = p.relative_to(detections_root).parts
            if "splunk" in (det.get("platforms") or []) and len(rel) > 2 and rel[0] == "splunk":
                packs[rel[1]] += 1
            sig = det.get("sigma")
            if isinstance(sig, dict) and sig.get("path"):
                sigma_meta += 1
    return {"packs": packs, "sigma_meta": sigma_meta, "sigma_files": sigma_files}


def render(root: Path) -> str:
    detections_root = root / "detections"
    s = build_coverage(detections_root)["summary"]
    extra = _extra_counts(detections_root)
    pc = s["platform_counts"]
    total = s["detections_total"]
    splunk, cs, mde = pc.get("splunk", 0), pc.get("crowdstrike", 0), pc.get("defender", 0)
    packs = " • ".join(
        f"{PACK_LABELS.get(k, k)} {v}" for k, v in sorted(extra["packs"].items(), key=lambda kv: (-kv[1], kv[0]))
    )
    pct = s["detections_with_mitre_percent"]
    pct_txt = f"{pct:g}%"
    lines: List[str] = [
        BEGIN,
        f"- **Total detections**: {total}",
        f"- **Rules per platform**: Splunk {splunk} • CrowdStrike {cs} • Defender {mde}",
        f"- **Splunk pack breakdown**: {packs}",
        f"- **ATT&CK coverage**: {s['unique_techniques']} unique techniques • tactics normalized from `mitre.tactics` "
        "(ATT&CK v19 remap: revoked T1562/T1070.001 folded into T1685/T1686)",
        f"- **ATT&CK mapping completeness**: {s['detections_with_mitre']}/{total} detections include `mitre.techniques` ({pct_txt})",
        "",
        "| Platform | Rules | Query format |",
        "| --- | ---: | --- |",
        f"| Splunk | {splunk} | SPL (`query.splunk`) |",
        f"| CrowdStrike Falcon | {cs} | CQL / Falcon IOA-style patterns (`query.crowdstrike`) |",
        f"| Microsoft Defender for Endpoint | {mde} | KQL Advanced Hunting (`query.defender`) |",
        f"| Sigma sources | {extra['sigma_files']} Sigma YAMLs under `detections/` | {extra['sigma_meta']} detections carry "
        "`sigma.path` metadata (Sigma→Splunk conversions) |",
        END,
    ]
    return "\n".join(lines)


def main(argv: List[str]) -> int:
    root = _repo_root()
    readme = root / "README.md"
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"{readme}: README_COUNTS markers not found", file=sys.stderr)
        return 2
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + render(root) + tail
    if "--check" in argv:
        if new != text:
            print("README.md counts are stale: run python pipelines/validate/build_readme_counts.py", file=sys.stderr)
            return 1
        print("OK: README.md counts match repo data")
        return 0
    readme.write_text(new, encoding="utf-8")
    print(f"Wrote counts block in {readme}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
